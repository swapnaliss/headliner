// docs/evidence/agent-evals.md, generated from the replay. Byte-stable: no run date, only the dates and commits of the
// recordings, so `git diff --exit-code docs/evidence/agent-evals.md` after a replay is the staleness check.
import { readdirSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { groundingCheck } from "../../packages/agent/src/index";
import { loadSlate } from "../../packages/agent/src/explain/testkit";
import { EVAL_TRACES, EXPLAIN_REPLIES, INTAKE_TRACES, RECORDINGS_MANIFEST, type Category, type CaseResult } from "./common";
import type { EvalOutput } from "./run";

export interface RecordingFacts {
  readonly intakeTraces: number;
  readonly explainReplies: number;
  readonly models: readonly string[];
  readonly firstAt: string;
  readonly lastAt: string;
  readonly tokens: number;
  readonly costUsd: number;
  readonly commits: readonly string[];
  readonly lookupCalls: number;
  readonly statuses: Readonly<Record<string, number>>;
}

interface TraceFile {
  model?: string;
  recordedAt?: string;
  turns?: { toolCalls: { name: string }[]; usage: { totalTokens: number }; costUsd: number }[];
  outcome?: { status?: string };
  usage?: { totalTokens: number };
  costUsd?: number;
}

const readDir = (dir: string): TraceFile[] =>
  readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .sort()
    .map((f) => JSON.parse(readFileSync(join(dir, f), "utf8")) as TraceFile);

export function loadRecordingFacts(): RecordingFacts {
  const intake = [...readDir(INTAKE_TRACES), ...readDir(EVAL_TRACES)];
  const explain = readDir(EXPLAIN_REPLIES);
  const all = [...intake, ...explain];
  const dates = all.map((t) => t.recordedAt ?? "").filter((d) => d !== "").sort();
  const manifest = JSON.parse(readFileSync(RECORDINGS_MANIFEST, "utf8")) as { entries: Record<string, { commit: string }> };
  const statuses: Record<string, number> = {};
  for (const t of intake) statuses[t.outcome?.status ?? "?"] = (statuses[t.outcome?.status ?? "?"] ?? 0) + 1;
  return {
    intakeTraces: intake.length,
    explainReplies: explain.length,
    models: [...new Set(all.map((t) => t.model ?? "?"))].sort(),
    firstAt: dates[0] ?? "?",
    lastAt: dates[dates.length - 1] ?? "?",
    tokens: intake.reduce((n, t) => n + (t.turns ?? []).reduce((m, x) => m + x.usage.totalTokens, 0), 0) + explain.reduce((n, t) => n + (t.usage?.totalTokens ?? 0), 0),
    costUsd: intake.reduce((n, t) => n + (t.turns ?? []).reduce((m, x) => m + x.costUsd, 0), 0) + explain.reduce((n, t) => n + (t.costUsd ?? 0), 0),
    commits: [...new Set(Object.values(manifest.entries).map((e) => e.commit))].sort(),
    lookupCalls: intake.reduce((n, t) => n + (t.turns ?? []).reduce((m, x) => m + x.toolCalls.filter((c) => c.name === "propose_matches").length, 0), 0),
    statuses,
  };
}

export interface GapProbe {
  readonly probe: string;
  readonly text: string;
  readonly caught: boolean;
}

/** Texts the grounding check is known not to be able to judge, run through the real check so the report states the current truth. */
export async function knownGaps(): Promise<GapProbe[]> {
  const slate = loadSlate("sample-leipzig-indie");
  const probes: { probe: string; text: string }[] = [
    { probe: "A lowercase invented act (the check finds invented names by their capital letter)", text: "radiohead would also suit this room well." },
    { probe: "A real Slate figure attached to the wrong meaning (a sentence a live model wrote in hs-instruction-name; 5 of 5 is the count of candidate acts)", text: "The room-wide audience-taste fit is 5 of 5 for the Leipzig regular crowd." },
  ];
  return probes.map((p) => ({ ...p, caught: !groundingCheck(p.text, slate).ok }));
}

const LABEL: Record<Category, string> = {
  groundTruth: "Ground truth (sentence to Room, recorded traces replayed)",
  trajectory: "Trajectory (steps, questions, tools, schema, typed Qloo calls) over every recorded trace",
  injection: "Injection corpus (act, city, sentence, manipulated model, explanation)",
  toolFailure: "Tool failures (adapter and model)",
  adversarial: "Prompt-injection set (hostile names, typed instructions, computed numbers, key exfiltration)",
};
const ORDER: Category[] = ["groundTruth", "trajectory", "injection", "toolFailure", "adversarial"];

function table(cases: readonly CaseResult[]): string {
  return ["| Case | Assertions | Result |", "|---|---|---|", ...cases.map((c) => `| ${c.id} | ${c.checks} | ${c.ok ? "pass" : "FAIL"} |`)].join("\n");
}

export function renderReport(out: EvalOutput, rec: RecordingFacts, gaps: readonly GapProbe[]): string {
  const lines: string[] = [];
  lines.push("# Agent evals (M3-03)", "");
  lines.push("Generated by `npm run eval:agent` from recorded traces. Offline: no key, no network, no database. Regenerate and diff with `npm run eval:agent && git diff --exit-code docs/evidence/agent-evals.md`.", "");
  lines.push("What it proves: the agent's guardrails (input limits, typed Qloo parameters, schema-validated output, names must come from the booker's sentence, the grounding check and the template fallback) hold against the recorded behaviour of a real model and against hand-written stand-ins for a model that obeys an injection. What it does not prove: that a model will never misbehave on a sentence nobody recorded; the guardrails, not the model, are what is tested.", "");
  lines.push("## Results", "", "| Category | Cases | Passed | Assertions |", "|---|---|---|---|");
  for (const cat of ORDER) {
    const cs = out.cases.filter((c) => c.category === cat);
    lines.push(`| ${LABEL[cat]} | ${cs.length} | ${cs.filter((c) => c.ok).length} | ${cs.reduce((n, c) => n + c.checks, 0)} |`);
  }
  lines.push(`| **Total** | **${out.cases.length}** | **${out.passed}** | **${out.cases.reduce((n, c) => n + c.checks, 0)}** |`, "");
  lines.push("The mutation check (`evals/agent/mutation.test.ts`, run by `npm test`) removes the encoding and shows these evals fail. Rendered-text escaping is checked by `evals/agent/render.test.tsx` against the real Explanation component, one test per injection string.", "");
  lines.push("## Recordings", "");
  lines.push(`- ${rec.intakeTraces} intake traces (\`fixtures/agent/intake/\`, \`fixtures/agent/evals/intake/\`) and ${rec.explainReplies} explanation replies (\`fixtures/agent/evals/explain/\`), all recorded live from ${rec.models.join(", ")}.`);
  lines.push(`- Recorded between ${rec.firstAt} and ${rec.lastAt}. The 4 traces in \`fixtures/agent/intake/\` were recorded in M3-01 (PR #76); the rest ran on top of commit${rec.commits.length === 1 ? "" : "s"} ${rec.commits.map((c) => `\`${c.slice(0, 7)}\``).join(", ")} (\`fixtures/agent/evals/recordings.json\`).`);
  lines.push(`- Measured from the recordings: ${rec.tokens.toLocaleString("en-US")} tokens, ${rec.costUsd.toFixed(4)} USD in total. Outcomes of the intake traces: ${Object.entries(rec.statuses).sort().map(([k, v]) => `${v} ${k}`).join(", ")}.`);
  lines.push(`- The recorded model called the optional lookup tool \`propose_matches\` ${rec.lookupCalls} times in ${rec.intakeTraces} traces, so the tool-result path is exercised by the scripted stand-in models and the failure cases, not by the live traces.`);
  lines.push("- Re-record (manual, live, needs `OPENAI_API_KEY`, never run in CI): `npm run eval:agent:record -- --force`.", "");
  lines.push("## Known gaps (measured by probing the real grounding check)", "", "| Probe | Caught |", "|---|---|", ...gaps.map((g) => `| ${g.probe}: \`${g.text}\` | ${g.caught ? "yes" : "no, accepted"} |`), "");
  for (const cat of ORDER) lines.push(`## ${LABEL[cat]}`, "", table(out.cases.filter((c) => c.category === cat)), "");
  return `${lines.join("\n")}\n`;
}
